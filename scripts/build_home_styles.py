#!/usr/bin/env python3
"""Inline homepage CSS to eliminate render-blocking stylesheet requests.

Run after editing style.css or photography.css. These files remain the source
of truth; the photography page continues to load its own external stylesheets.
Use --check in validation to detect an out-of-date generated block.
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START = '<!-- Generated by scripts/build_home_styles.py; edit the source CSS files. -->'
END = '<!-- End generated homepage styles. -->'


def preview_rules(css):
    """Keep preview rules and their media conditions, in original cascade order."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    result = []
    cursor = 0
    while cursor < len(css):
        opening = css.find('{', cursor)
        if opening < 0:
            break
        selector = css[cursor:opening].strip()
        depth, end = 1, opening + 1
        while depth:
            if css[end] == '{':
                depth += 1
            elif css[end] == '}':
                depth -= 1
            end += 1
        body = css[opening + 1:end - 1]
        if selector.startswith('@media'):
            nested = preview_rules(body)
            if nested:
                result.append(f'{selector} {{\n{nested}\n}}')
        elif selector.startswith(('.photo-preview-', '.preview-')):
            result.append(f'{selector} {{{body}}}')
        cursor = end
    return '\n'.join(result)


def build(check=False):
    page = ROOT / 'index.html'
    html = page.read_text()
    css = (ROOT / 'style.css').read_text().rstrip()
    preview = preview_rules((ROOT / 'photography.css').read_text())
    assert '.photo-preview-grid' in preview
    assert '@media (max-width: 480px)' in preview
    block = f'{START}\n    <style id="homepage-styles">\n{css}\n\n/* Homepage photography preview only. */\n{preview}\n    </style>\n    {END}'
    if START in html:
        updated = re.sub(re.escape(START) + r'.*?' + re.escape(END), lambda _: block, html, count=1, flags=re.S)
    else:
        updated, count = re.subn(r'<link rel="stylesheet" href="style\.css[^\"]*">\s*<link rel="stylesheet" href="photography\.css">', lambda _: block, html, count=1)
        assert count == 1, 'Homepage stylesheet links not found'
    if check:
        if updated != html:
            raise SystemExit('Homepage styles are stale. Run python3 scripts/build_home_styles.py')
        print('Homepage inline styles are up to date.')
    else:
        page.write_text(updated)
        print(f'Inlined {len(css.encode()):,} bytes of main CSS and {len(preview.encode()):,} bytes of preview CSS.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    build(parser.parse_args().check)
