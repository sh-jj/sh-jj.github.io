#!/usr/bin/env python3
"""Scan photo folders and generate the static gallery's data and web-sized images.
Run from anywhere: python3 scripts/build_photography.py
Original files are read only. Empty albums never enter the generated catalog.
"""
import argparse
import hashlib
import io
import json
import re
from datetime import datetime
from pathlib import Path
from PIL import Image, ImageOps, ImageCms

ROOT = Path(__file__).resolve().parents[1]
EXTENSIONS = {'.jpg', '.jpeg', '.png', '.webp'}


def photo_date(name, year):
    match = re.search(r'(?<!\d)(20\d{6})(?!\d)', name)
    if match:
        try:
            return datetime.strptime(match[1], '%Y%m%d').date().isoformat()
        except ValueError:
            pass
    return year


def build(source, destination, catalog):
    destination.mkdir(parents=True, exist_ok=True)
    assets = destination / 'images'
    assets.mkdir(exist_ok=True)
    albums, keep = [], set()
    for folder in sorted(source.iterdir() if source.exists() else []):
        if not folder.is_dir() or not re.match(r'^\d{4}-.+', folder.name):
            continue
        year, location = folder.name.split('-', 1)
        country_slug = next((c for c in ('south-korea', 'united-states', 'united-kingdom')
                             if location.startswith(c + '-')), location.split('-')[0])
        place_slug = location[len(country_slug) + 1:]
        meta = catalog.get('albums', {}).get(folder.name, {})
        album = dict(id=folder.name, year=year,
                     place=meta.get('place', place_slug.replace('-', ' ').title()),
                     localPlace=meta.get('localPlace', ''),
                     country=meta.get('country', country_slug.replace('-', ' ').title()),
                     description=meta.get('description', ''), photos=[])
        for path in sorted(folder.iterdir()):
            if not path.is_file() or path.name.startswith('.') or path.suffix.lower() not in EXTENSIONS:
                continue
            stat = path.stat()
            key = hashlib.sha256(f'v2/{folder.name}/{path.name}/{stat.st_size}/{stat.st_mtime_ns}'.encode()).hexdigest()[:16]
            try:
                with Image.open(path) as original:
                    oriented = ImageOps.exif_transpose(original)
                    width, height = oriented.size
                    rgb = oriented.convert('RGB')
                    if original.info.get('icc_profile'):
                        rgb = ImageCms.profileToProfile(rgb,
                            ImageCms.ImageCmsProfile(io.BytesIO(original.info['icc_profile'])),
                            ImageCms.createProfile('sRGB'), outputMode='RGB')
                    for label, size, quality in [('thumb', 800, 80), ('large', 2400, 86)]:
                        target = assets / f'{key}-{label}.webp'
                        keep.add(target.name)
                        if not target.exists():
                            image = rgb.copy()
                            image.thumbnail((size, size), Image.Resampling.LANCZOS)
                            # Export without location metadata; originals retain their metadata.
                            image.save(target, 'WEBP', quality=quality, method=4)
            except (OSError, ValueError) as error:
                raise RuntimeError(f'Cannot process {path}: {error}') from error
            titles = catalog.get('photos', {}).get(f'{folder.name}/{path.name}',
                         catalog.get('photos', {}).get(path.name))
            fallback = re.sub(r'[-_]?20\d{6}$', '', path.stem)
            if not titles:
                titles = [fallback, '']
            album['photos'].append(dict(id=key, filename=path.name, title=titles[0],
                localTitle=titles[1] if len(titles) > 1 else '', date=photo_date(path.stem, year),
                width=width, height=height,
                thumbWidth=round(width * min(1, 800 / max(width, height))),
                largeWidth=round(width * min(1, 2400 / max(width, height))),
                thumb=f'photography/images/{key}-thumb.webp',
                src=f'photography/images/{key}-large.webp'))
        if not album['photos']:
            continue
        album['photos'].sort(key=lambda p: (p['filename'] != meta.get('cover'), p['filename']))
        albums.append(album)
    albums.sort(key=lambda a: (-int(a['year']), -max(int(p['date'].replace('-', '').ljust(8, '0')) for p in a['photos']), a['place']))
    payload = json.dumps(albums, ensure_ascii=False, indent=2)
    (destination / 'data.js').write_text('// Generated by scripts/build_photography.py; edit catalog.json instead.\nwindow.PHOTO_ALBUMS = ' + payload + ';\n', encoding='utf-8')
    for path in assets.glob('*.webp'):
        if path.name not in keep:
            path.unlink()
    print(f'Built {len(albums)} albums, {sum(len(a["photos"]) for a in albums)} photographs. Empty folders excluded.')
    return albums


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT / 'img/photography')
    parser.add_argument('--output', type=Path, default=ROOT / 'photography')
    parser.add_argument('--catalog', type=Path, default=ROOT / 'photography/catalog.json')
    args = parser.parse_args()
    config = json.loads(args.catalog.read_text(encoding='utf-8')) if args.catalog.exists() else {}
    build(args.source, args.output, config)
